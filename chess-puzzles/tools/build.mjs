// Builds puzzles.js from generator output.
// Usage: node tools/build.mjs m1.json m2.json [m3.json ...]  (file i = mate in i+1)
import { readFileSync, writeFileSync } from 'node:fs';
import { Chess } from '../vendor/chess.js';
import { canMate, mateKeys } from '../solver.js';

const flipSq = s => s[0] + (9 - Number(s[1]));
function flipFen(fen) {
  const [board] = fen.split(' ');
  const rows = board.split('/').reverse().map(r => r.replace(/[a-z]/gi, c => c === c.toUpperCase() ? c.toLowerCase() : c.toUpperCase()));
  return rows.join('/') + ' b - - 0 1';
}
const flipUci = u => flipSq(u.slice(0, 2)) + flipSq(u.slice(2, 4)) + (u[4] || '');

const INFO = [
  { title: 'Mate in one', desc: 'Find the move that checkmates immediately. Exactly one move works in each position.' },
  { title: 'Mate in two', desc: 'Find the key move; every defence then allows mate. No mate in one exists, and the key is unique. The computer answers with its most stubborn reply.' },
  { title: 'Mate in three', desc: 'Three moves to force checkmate against the best defence.' },
];

const chapters = process.argv.slice(2).map((file, i) => {
  const n = i + 1;
  const seen = new Set();
  const list = JSON.parse(readFileSync(file, 'utf8'))
    .filter(p => !seen.has(p.fen.split(' ')[0]) && seen.add(p.fen.split(' ')[0]))
    .sort((a, b) => a.pieces - b.pieces || Number(b.check) - Number(a.check));
  const puzzles = list.map((p, j) => {
    const flip = j % 3 === 1; // about a third with Black to move
    const fen = flip ? flipFen(p.fen) : p.fen;
    const line = flip ? p.line.map(flipUci) : p.line;
    const g = new Chess(fen);
    const keys = mateKeys(g, n);
    if (keys.length !== 1 || keys[0].lan !== line[0] || (n > 1 && canMate(g, n - 1))) throw new Error('verify failed ' + fen);
    return [fen, line.join(' ')];
  });
  return { id: `m${n}`, mate: n, ...INFO[i], puzzles };
});

const out = `// Generated by tools/build.mjs — original computer-generated, solver-verified positions.
// Format: [FEN, main line in UCI]
export const CHAPTERS = ${JSON.stringify(chapters, null, 0).replace(/\],\[/g, '],\n[')};
`;
writeFileSync(new URL('../puzzles.js', import.meta.url), out);
console.log(chapters.map(c => `${c.title}: ${c.puzzles.length}`).join('\n'));
